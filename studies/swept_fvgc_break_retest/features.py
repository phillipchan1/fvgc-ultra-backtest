class CandleIndex:
    """Holds candle arrays + per-date RTH-open index for fast as-of slicing."""

    def __init__(self, candles: pd.DataFrame):
        self.high = candles['high'].to_numpy(dtype=float)
        self.low = candles['low'].to_numpy(dtype=float)
        self.close = candles['close'].to_numpy(dtype=float)
        self.open = candles['open'].to_numpy(dtype=float)
        self.vol = candles['volume'].to_numpy(dtype=float)
        ts_ny = candles['timestamp_ny']
        self.date = ts_ny.dt.date.to_numpy()
        self.tod = ts_ny.dt.time.to_numpy()
        # utc ns for exact created_at -> idx lookup
        self.ts_utc_ns = candles['timestamp_utc'].astype('int64').to_numpy()
        self.ts_ny = ts_ny.to_numpy()
        self.n = len(candles)

        # per-date [start, end) bounds and rth_open_idx
        self.date_start: dict[Any, int] = {}
        self.date_end: dict[Any, int] = {}
        self.rth_open_idx: dict[Any, int] = {}
        prev = None
        start = 0
        for i in range(self.n):
            d = self.date[i]
            if d != prev:
                if prev is not None:
                    self.date_end[prev] = i
                self.date_start[d] = i
                prev = d
        if prev is not None:
            self.date_end[prev] = self.n
        for d, s in self.date_start.items():
            e = self.date_end[d]
            ro = None
            for i in range(s, e):
                if self.tod[i] >= RTH_OPEN:
                    ro = i
                    break
            if ro is not None:
                self.rth_open_idx[d] = ro

    def idx_for_utc_ns(self, ns: int) -> Optional[int]:
        j = int(np.searchsorted(self.ts_utc_ns, ns))
        if 0 <= j < self.n and self.ts_utc_ns[j] == ns:
            return j
        return None


