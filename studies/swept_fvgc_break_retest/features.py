# Daily regime precompute (causal: every series shifted to PRIOR day)
# ===================================================================

def build_daily_context() -> pd.DataFrame:
    """Per-date regime context using ONLY information available at 9:30.

    Returns a DataFrame indexed by date with:
      atr14            : 14-day ATR through the PRIOR session (shift 1).
      ema20, ema50     : daily-close EMAs through the PRIOR session (shift 1).
      macro_trend      : {'up','down','flat'} from price-vs-EMA + EMA slope (prior).
      prior_vp_poc/vah/val/width : PRIOR trading day's RTH volume profile (lag-1).
      vixy_regime, prior_day_type, gap_from_prior_close, rth_open : same-day open info.
    """
    td = pd.read_csv(TRADING_DAYS)
    td['date'] = pd.to_datetime(td['date']).dt.date
    td = td.sort_values('date').reset_index(drop=True)

    # True range from daily RTH OHLC; ATR14 through prior day (shift 1).
    h, l, c = td['rth_high'], td['rth_low'], td['rth_close']
    prev_close = c.shift(1)
    tr = pd.concat([(h - l), (h - prev_close).abs(), (l - prev_close).abs()], axis=1).max(axis=1)
    td['atr14'] = tr.rolling(14, min_periods=5).mean().shift(1)

    td['ema20'] = c.ewm(span=20, adjust=False).mean().shift(1)
    td['ema50'] = c.ewm(span=50, adjust=False).mean().shift(1)
    ema20_slope = (td['ema20'] - td['ema20'].shift(1))
    # macro_trend: price (prior close) vs ema, confirmed by ema20 slope sign.
    pc = prev_close
    up = (pc > td['ema20']) & (td['ema20'] > td['ema50']) & (ema20_slope > 0)
    dn = (pc < td['ema20']) & (td['ema20'] < td['ema50']) & (ema20_slope < 0)
    td['macro_trend'] = np.where(up, 'up', np.where(dn, 'down', 'flat'))

    # lag-1 volume profile
    vp = pd.read_csv(DAILY_VP)
    vp['date'] = pd.to_datetime(vp['date']).dt.date
    vp = vp.sort_values('date').reset_index(drop=True)
    vp['prior_vp_poc'] = vp['poc'].shift(1)
    vp['prior_vp_vah'] = vp['vah'].shift(1)
    vp['prior_vp_val'] = vp['val'].shift(1)
    vp['prior_vp_width'] = vp['va_width'].shift(1)
    vp_lag = vp[['date', 'prior_vp_poc', 'prior_vp_vah', 'prior_vp_val', 'prior_vp_width']]

    keep = ['date', 'atr14', 'ema20', 'ema50', 'macro_trend',
            'vixy_regime', 'prior_day_type', 'gap_from_prior_close', 'rth_open',
            'or_5min_high', 'or_5min_low', 'or_15min_high', 'or_15min_low',
            'or_45min_high', 'or_45min_low']
    ctx = td[keep].merge(vp_lag, on='date', how='left')
    return ctx.set_index('date')


