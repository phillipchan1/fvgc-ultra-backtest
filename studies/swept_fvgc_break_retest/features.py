def load_levels_by_date() -> dict[Any, pd.DataFrame]:
    liqu = pd.read_csv(LIQUIDITY)
    liqu['date'] = pd.to_datetime(liqu['date']).dt.date
    out: dict[Any, pd.DataFrame] = {}
    for d, grp in liqu.groupby('date'):
        out[d] = grp.reset_index(drop=True)
    return out


def parse_avail_time(val: Any) -> Optional[dtime]:
    s = str(val).strip().lower()
    if s in ('', 'nan', 'none', 'open'):
        return None
    try:
        hh, mm = s.split(':')
        return dtime(int(hh), int(mm))
    except (ValueError, AttributeError):
        return None


def build_level_candidates(
    day_levels: Optional[pd.DataFrame],
    entry_tod: dtime,
    ctx_row: pd.Series,
    rth_lo: float,
    rth_hi: float,
) -> list[dict]:
    """All level candidates valid AS-OF entry time-of-day.

    Each candidate: {price, group, side, is_stop_liquidity, is_htf, htf_tf,
                     fvg_dir, fvg_top, fvg_bottom, bars_old}.
    Mean-reversion magnets (VWAP/POC) are added by the caller, not here.

    Availability gate: only levels whose `available_time` <= entry_tod (the same
    gate the production pipeline uses) — prevents e.g. OR levels (avail 09:45)
    leaking into pre-09:45 signals.
    """
    cands: list[dict] = []
    if day_levels is not None and not day_levels.empty:
        flt = filter_trade_date_levels(day_levels)
        for _, r in flt.iterrows():
            px = r.get('price')
            if px is None or (isinstance(px, float) and np.isnan(px)):
                continue
            at = parse_avail_time(r.get('available_time'))
            if at is not None and entry_tod < at:
                continue
            group = str(r.get('group'))
            tf = r.get('timeframe')
            is_htf = pd.notna(tf) and str(tf).strip() not in ('', 'nan', 'none')
            fvg_dir = str(r.get('fvg_direction')) if is_htf else ''
            side = str(r.get('side'))
            bars_old = r.get('bars_old')
            cands.append({
                'price': float(px),
                'group': group,
                'side': side,
                'is_stop_liquidity': group in STOP_LIQUIDITY_GROUPS,
                'is_htf': bool(is_htf),
                'htf_tf': str(tf) if is_htf else '',
                'fvg_dir': fvg_dir,
                'fvg_top': float(r['fvg_top']) if is_htf and pd.notna(r.get('fvg_top')) else np.nan,
                'fvg_bottom': float(r['fvg_bottom']) if is_htf and pd.notna(r.get('fvg_bottom')) else np.nan,
                'bars_old': float(bars_old) if pd.notna(bars_old) else np.nan,
            })

    # Round-number levels within the session range (stop-liquidity, always avail).
    for grid, tag in ((ROUND_100, 'round_100'), (ROUND_50, 'round_50')):
        lo = int(np.floor(rth_lo / grid)) * grid
        hi = int(np.ceil(rth_hi / grid)) * grid
        p = lo
        while p <= hi:
            cands.append({
                'price': float(p), 'group': tag, 'side': 'both',
                'is_stop_liquidity': True, 'is_htf': False, 'htf_tf': '',
                'fvg_dir': '', 'fvg_top': np.nan, 'fvg_bottom': np.nan,
                'bars_old': np.nan,
            })
            p += grid
    return cands


# ===================================================================
# §4.1 Intraday sweep + recency  (as-of: RTH bars 9:30 -> fvg_created)
# ===================================================================

def _bars_since_sweep_bucket(b: Optional[int]) -> str:
    if b is None:
        return 'none'
    if b <= 5:
        return '0-5'
    if b <= 15:
        return '5-15'
    if b <= 60:
        return '15-60'
    return '>60'


def detect_swept_level(
    ci: CandleIndex, d: Any, created_idx: int, direction: str,
    fvg_top: float, fvg_bottom: float, fvg_size: float,
    cands: list[dict],
) -> dict:
    """Find the most-recent STOP-LIQUIDITY level interaction the FVG sits at.

    As-of window: RTH bars [rth_open, created_idx) ONLY — the interaction must
    precede the FVG's formation, so no information after the FVG is read.

    Per Phil: an interaction does NOT require a strict wick-past-and-close-back.
    A "reach" of the level counts as the swept interaction; `sweep_reclaim`
    records whether that bar also closed back on the favorable side (grab) vs
    merely tagged/penetrated it (tag). Phase B can split reclaim vs tag.

    long  signal -> support-type level reached (low<=L); reclaim = close>L.
    short signal -> resistance-type level reached (high>=L); reclaim = close<L.

    "Sits at": level price within FVG zone padded by max(LEVEL_PAD, 0.5*fvg_size).
    Returns swept(bool), bars_since_sweep, provenance, level price, reclaim flag.
    """
    pad = max(LEVEL_PAD, 0.5 * fvg_size)
    zone_lo, zone_hi = fvg_bottom - pad, fvg_top + pad
    ro = ci.rth_open_idx.get(d)
    out = {
        'swept': False, 'bars_since_sweep': None, 'bars_since_sweep_bucket': 'none',
        'swept_level_provenance': '', 'swept_level_price': np.nan,
        'sweep_reclaim': None, 'sweep_type': 'none',
    }
    if ro is None or created_idx <= ro:
        return out

    # candidate levels coinciding with the FVG zone (stop-liquidity only)
    coincident = [c for c in cands
                  if c['is_stop_liquidity'] and zone_lo <= c['price'] <= zone_hi]
    if not coincident:
        return out

    best_sweep_idx = -1
    best = None
    for c in coincident:
        L = c['price']
        for j in range(ro, created_idx):
            if direction == 'long':
                reached = ci.low[j] <= L
                reclaim = reached and ci.close[j] > L
            else:
                reached = ci.high[j] >= L
                reclaim = reached and ci.close[j] < L
            if reached and j > best_sweep_idx:
                best_sweep_idx = j
                best = (c, reclaim)
    if best is None:
        return out

    c, reclaim = best
    out['swept'] = True
    out['bars_since_sweep'] = created_idx - best_sweep_idx
    out['bars_since_sweep_bucket'] = _bars_since_sweep_bucket(out['bars_since_sweep'])
    out['swept_level_provenance'] = c['group']
    out['swept_level_price'] = c['price']
    out['sweep_reclaim'] = bool(reclaim)
    out['sweep_type'] = 'reclaim' if reclaim else 'tag'
    return out


# ===================================================================
# §4.2 break -> retest timing  (as-of: bars [created, entry])
# ===================================================================

def break_to_retest(
    ci: CandleIndex, created_idx: int, entry_idx: int, direction: str,
    fvg_top: float, fvg_bottom: float,
) -> dict:
    """bars from structural break (first close beyond FVG far edge in trade
    direction, the displacement leg) to the FVGC entry candle.

    As-of window: bars [created_idx, entry_idx] only. Causal by construction.
    NA when no break precedes entry (entry is then not a true break-&-retest).
    """
    break_idx = None
    for j in range(created_idx, entry_idx + 1):
        if direction == 'long' and ci.close[j] > fvg_top:
            break_idx = j
            break
        if direction == 'short' and ci.close[j] < fvg_bottom:
            break_idx = j
            break
    if break_idx is None:
        return {'has_break': False, 'bars_break_to_retest': None,
                'bars_break_to_retest_bucket': 'none',
                'break_to_retest_min': None, 'retest_within_10min': None}
    b = entry_idx - break_idx
    mins = b * 0.5  # 30s bars
    if b <= 1:
        bucket = '0-1'
    elif b <= 3:
        bucket = '2-3'
    elif b <= 6:
        bucket = '4-6'
    elif b <= 12:
        bucket = '7-12'
    else:
        bucket = '>12'
    return {'has_break': True, 'bars_break_to_retest': b,
            'bars_break_to_retest_bucket': bucket,
            'break_to_retest_min': mins,
            'retest_within_10min': b <= 20}  # 10 min = 20 x 30s bars


# ===================================================================
# §4.3 next untested magnet  (as-of: RTH bars 9:30 -> entry for untested check)
# ===================================================================

def level_untested_asof(ci: CandleIndex, d: Any, entry_idx: int, price: float) -> bool:
    """True if no RTH bar in [rth_open, entry_idx) traded through `price`."""
    ro = ci.rth_open_idx.get(d)
    if ro is None:
        return True
    for j in range(ro, entry_idx):
        if ci.low[j] <= price <= ci.high[j]:
            return False
    return True


def next_magnet(
    ci: CandleIndex, d: Any, entry_idx: int, entry: float, direction: str,
    sl_dist: float, fvg_size: float, atr: float,
    cands: list[dict], mr_magnets: list[tuple[float, str]],
) -> dict:
    """Nearest UNTESTED magnet past entry in trade direction.

    Magnet universe = stop-liquidity levels + mean-reversion magnets (VWAP/POC/VA).
    As-of: untested status uses RTH bars up to entry only; all level prices are
    known at-or-before entry. clean_runway = no opposing level between entry and
    the magnet.
    """
    all_mags: list[tuple[float, str]] = [(c['price'], c['group']) for c in cands]
    all_mags += mr_magnets

    if direction == 'long':
        ahead = [(p, g) for p, g in all_mags if p > entry]
        ahead.sort(key=lambda x: x[0])
    else:
        ahead = [(p, g) for p, g in all_mags if p < entry]
        ahead.sort(key=lambda x: -x[0])

    magnet_price = None
    magnet_group = None
    for p, g in ahead:
        if level_untested_asof(ci, d, entry_idx, p):
            magnet_price, magnet_group = p, g
            break

    out = {
        'magnet_price': np.nan, 'magnet_group': '', 'magnet_dist_pts': np.nan,
        'magnet_dist_R': np.nan, 'magnet_dist_per_fvg': np.nan,
        'magnet_dist_per_atr': np.nan, 'clean_runway': None,
    }
    if magnet_price is None:
        return out
    dist = abs(magnet_price - entry)
    out['magnet_price'] = magnet_price
    out['magnet_group'] = magnet_group
    out['magnet_dist_pts'] = dist
    out['magnet_dist_R'] = dist / sl_dist if sl_dist and sl_dist > 0 else np.nan
    out['magnet_dist_per_fvg'] = dist / fvg_size if fvg_size > 0 else np.nan
    out['magnet_dist_per_atr'] = dist / atr if atr and atr > 0 else np.nan

    # clean runway: no OTHER level strictly between entry and the magnet
    blocked = False
    lo, hi = (entry, magnet_price) if entry < magnet_price else (magnet_price, entry)
    for p, g in all_mags:
        if lo < p < hi and abs(p - magnet_price) > 1e-9:
            blocked = True
            break
    out['clean_runway'] = not blocked
    return out


# ===================================================================
# §4.5 level-state qualifiers for the swept level (as-of RTH -> entry)
# ===================================================================

def level_state(
    ci: CandleIndex, d: Any, entry_idx: int, level_price: float, pad: float,
) -> dict:
    """virgin / touch_count for the swept level using RTH bars [rth_open, entry)."""
    ro = ci.rth_open_idx.get(d)
    out = {'level_touch_count': None, 'level_virgin': None}
    if ro is None or np.isnan(level_price):
        return out
    touches = 0
    for j in range(ro, entry_idx):
        if ci.low[j] - pad <= level_price <= ci.high[j] + pad:
            touches += 1
    out['level_touch_count'] = touches
    out['level_virgin'] = touches <= 1
    return out


# ===================================================================
# §4.6 nested HTF gap  (as-of: HTF FVG pre-exists; position from entry price)
# ===================================================================

def nested_htf(entry: float, direction: str, cands: list[dict]) -> dict:
    """Is entry inside an unfilled HTF FVG, and where within it?

    position_within_gap: 0 at the near (entry-side) edge, 1 at the far edge in
    the trade-continuation direction. High position => trading INTO the far edge
    (likely HTF resistance/fade); low position => open runway toward far edge.
    As-of: HTF FVG bounds are pre-session/pre-entry; entry price is known. Causal.
    """
    out = {'inside_htf_fvg': False, 'htf_nest_tf': '', 'htf_position_within_gap': np.nan,
           'htf_aligned': None}
    best = None
    for c in cands:
        if not c['is_htf']:
            continue
        top, bot = c['fvg_top'], c['fvg_bottom']
        if np.isnan(top) or np.isnan(bot):
            continue
        if bot <= entry <= top:
            width = top - bot
            if width <= 0:
                continue
            # far edge in trade direction
            if direction == 'long':
                pos = (entry - bot) / width  # 0 at bottom(near), 1 at top(far)
                aligned = (c['fvg_dir'] == 'bullish')
            else:
                pos = (top - entry) / width  # 0 at top(near), 1 at bottom(far)
                aligned = (c['fvg_dir'] == 'bearish')
            # prefer the smallest-TF nesting? keep the one with widest gap (most structural)
            if best is None or width > best[0]:
                best = (width, c['htf_tf'], pos, aligned)
    if best is not None:
        out['inside_htf_fvg'] = True
        out['htf_nest_tf'] = best[1]
        out['htf_position_within_gap'] = round(best[2], 4)
        out['htf_aligned'] = bool(best[3])
    return out


