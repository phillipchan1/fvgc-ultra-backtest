def va_position(price: float, vah: float, val: float) -> str:
    if np.isnan(vah) or np.isnan(val):
        return 'unknown'
    if price > vah:
        return 'above'
    if price < val:
        return 'below'
    return 'inside'


def enrich(sample: Optional[int] = None) -> pd.DataFrame:
    t0 = _time.time()
    candles = load_candles(CONS_30S)
    ci = CandleIndex(candles)
    print(f"  CandleIndex built: {_time.time()-t0:.1f}s, n={ci.n:,}")

    ctx = build_daily_context()
    levels_by_date = load_levels_by_date()
    print(f"  Context: {len(ctx)} days, levels: {len(levels_by_date)} days")

    sig = pd.read_csv(BASELINE)
    sig['ts'] = pd.to_datetime(sig['timestamp'])
    sig['fvg_created_ts'] = pd.to_datetime(sig['fvg_created_at'])
    if sample:
        sig = sig.iloc[:sample].copy()

    def to_utc_ns(ts: pd.Timestamp) -> int:
        """NY-local naive (or tz-aware) timestamp -> UTC ns (matches ci.ts_utc_ns)."""
        if ts.tzinfo is None:
            ts = ts.tz_localize('America/New_York')
        return int(ts.tz_convert('UTC').value)

    align_fail = 0     # signals whose entry_idx doesn't match its timestamp
    created_fail = 0   # signals whose fvg_created_at didn't resolve to a bar
    rows = []
    for _, s in sig.iterrows():
        entry_idx = int(s['entry_idx'])
        d = s['ts'].date()
        direction = str(s['direction'])
        entry = float(s['entry_price'])
        fvg_top = float(s['fvg_top'])
        fvg_bottom = float(s['fvg_bottom'])
        fvg_size = abs(fvg_top - fvg_bottom)
        try:
            sl_dist = float(s.get('sl_dist'))
        except (TypeError, ValueError):
            sl_dist = np.nan

        # entry_idx alignment guard: bar at entry_idx must equal the signal bar.
        if not (0 <= entry_idx < ci.n) or ci.ts_utc_ns[entry_idx] != to_utc_ns(s['ts']):
            align_fail += 1
            continue  # skip mis-indexed signal rather than emit bad features

        created_idx = ci.idx_for_utc_ns(to_utc_ns(s['fvg_created_ts']))
        if created_idx is None:
            created_idx = max(0, entry_idx - 1)
            created_fail += 1

        ctx_row = ctx.loc[d] if d in ctx.index else None
        atr = float(ctx_row['atr14']) if ctx_row is not None and pd.notna(ctx_row['atr14']) else np.nan

        # day RTH slice up to entry (for round-grid range, dev VP, untested checks)
        ro = ci.rth_open_idx.get(d)
        rth_lo = float(np.min(ci.low[ro:entry_idx + 1])) if ro is not None else entry
        rth_hi = float(np.max(ci.high[ro:entry_idx + 1])) if ro is not None else entry

        entry_tod = s['ts'].time()
        day_levels = levels_by_date.get(d)
        cands = build_level_candidates(day_levels, entry_tod, ctx_row, rth_lo, rth_hi)

        # --- mean-reversion magnets (VWAP, lag-1 VP, developing VP) ---
        mr_magnets: list[tuple[float, str]] = []
        # session VWAP as-of entry
        vwap_val = np.nan
        if ro is not None:
            day_df = candles.iloc[ci.date_start[d]:ci.date_end[d]]
            vser = session_vwap(day_df)
            # value at entry_idx (absolute) -> position within day_df
            rel = entry_idx - ci.date_start[d]
            if 0 <= rel < len(vser):
                vwap_val = float(vser.iloc[rel]) if pd.notna(vser.iloc[rel]) else np.nan
        if not np.isnan(vwap_val):
            mr_magnets.append((vwap_val, 'vwap'))

        prior_poc = float(ctx_row['prior_vp_poc']) if ctx_row is not None and pd.notna(ctx_row.get('prior_vp_poc')) else np.nan
        prior_vah = float(ctx_row['prior_vp_vah']) if ctx_row is not None and pd.notna(ctx_row.get('prior_vp_vah')) else np.nan
        prior_val = float(ctx_row['prior_vp_val']) if ctx_row is not None and pd.notna(ctx_row.get('prior_vp_val')) else np.nan
        for p, tag in ((prior_poc, 'prior_poc'), (prior_vah, 'prior_vah'), (prior_val, 'prior_val')):
            if not np.isnan(p):
                mr_magnets.append((p, tag))

        # developing VP up to entry
        dev = None
        if ro is not None:
            day_rth = candles.iloc[ro:entry_idx + 1]
            dev = developing_vp(day_rth)
        dev_poc = dev['poc'] if dev else np.nan
        dev_vah = dev['vah'] if dev else np.nan
        dev_val = dev['val'] if dev else np.nan
        if dev:
            mr_magnets.append((dev_poc, 'dev_poc'))

        # --- features ---
        sw = detect_swept_level(ci, d, created_idx, direction, fvg_top, fvg_bottom, fvg_size, cands)
        br = break_to_retest(ci, created_idx, entry_idx, direction, fvg_top, fvg_bottom)
        mag = next_magnet(ci, d, entry_idx, entry, direction, sl_dist, fvg_size, atr, cands, mr_magnets)
        pad = max(LEVEL_PAD, 0.5 * fvg_size)
        lst = level_state(ci, d, entry_idx, sw['swept_level_price'], pad)
        nh = nested_htf(entry, direction, cands)

        # VWAP location
        vwap_dist = (entry - vwap_val) if not np.isnan(vwap_val) else np.nan
        if direction == 'short' and not np.isnan(vwap_dist):
            vwap_dist_signed = -vwap_dist  # +ve = in trade-favorable side (above for short)
        else:
            vwap_dist_signed = vwap_dist
        vwap_above = (entry > vwap_val) if not np.isnan(vwap_val) else None
        r0_ge_10 = (abs(vwap_dist) >= 10.0) if not np.isnan(vwap_dist) else None

        # VA position (lag-1 and developing)
        va_pos_prior = va_position(entry, prior_vah, prior_val)
        va_pos_dev = va_position(entry, dev_vah, dev_val) if dev else 'unknown'

        # confluence stack: distinct groups within FVG zone +/- 10pt
        stack_groups = set()
        for c in cands:
            if abs(c['price'] - (fvg_top + fvg_bottom) / 2) <= 10.0:
                stack_groups.add(c['group'])
        confluence_stack = len(stack_groups)

        # regime: intraday — open vs prior VA, OR width (availability-gated), price vs dev VWAP/POC
        rth_open_px = float(ctx_row['rth_open']) if ctx_row is not None and pd.notna(ctx_row.get('rth_open')) else np.nan
        open_vs_prior_va = va_position(rth_open_px, prior_vah, prior_val)
        # OR width available as-of entry: widest OR window whose end <= entry_tod
        or_width = np.nan
        if ctx_row is not None:
            if entry_tod >= dtime(10, 15) and pd.notna(ctx_row.get('or_45min_high')):
                or_width = float(ctx_row['or_45min_high']) - float(ctx_row['or_45min_low'])
            elif entry_tod >= dtime(9, 45) and pd.notna(ctx_row.get('or_15min_high')):
                or_width = float(ctx_row['or_15min_high']) - float(ctx_row['or_15min_low'])
            elif entry_tod >= dtime(9, 35) and pd.notna(ctx_row.get('or_5min_high')):
                or_width = float(ctx_row['or_5min_high']) - float(ctx_row['or_5min_low'])
        price_vs_dev_vwap = (entry > vwap_val) if not np.isnan(vwap_val) else None
        price_vs_dev_poc = (entry > dev_poc) if dev else None

        macro_trend = str(ctx_row['macro_trend']) if ctx_row is not None else 'flat'
        vixy_regime = str(ctx_row['vixy_regime']) if ctx_row is not None and pd.notna(ctx_row.get('vixy_regime')) else 'unknown'
        prior_day_type = str(ctx_row['prior_day_type']) if ctx_row is not None and pd.notna(ctx_row.get('prior_day_type')) else 'unknown'

        # direction x regime alignment
        if macro_trend == 'up':
            regime_alignment = 'aligned' if direction == 'long' else 'counter'
        elif macro_trend == 'down':
            regime_alignment = 'aligned' if direction == 'short' else 'counter'
        else:
            regime_alignment = 'flat'

        row = {
            **s.drop(labels=['ts', 'fvg_created_ts']).to_dict(),
            'created_idx': created_idx,
            'atr14': atr,
            # 4.1
            **sw,
            # 4.2
            **br,
            # 4.3
            **mag,
            # 4.4 vwap / VA
            'vwap': vwap_val, 'vwap_dist_pts': vwap_dist, 'vwap_dist_signed': vwap_dist_signed,
            'vwap_above': vwap_above, 'r0_ge_10pt': r0_ge_10,
            'va_pos_prior': va_pos_prior, 'va_pos_dev': va_pos_dev,
            # 4.5
            **lst, 'confluence_stack': confluence_stack,
            # 4.6
            **nh,
            # 4.7 regime
            'macro_trend': macro_trend, 'vixy_regime': vixy_regime,
            'prior_day_type': prior_day_type, 'regime_alignment': regime_alignment,
            'open_vs_prior_va': open_vs_prior_va, 'or_width_asof': or_width,
            'price_above_dev_vwap': price_vs_dev_vwap, 'price_above_dev_poc': price_vs_dev_poc,
            # dev VP raw
            'dev_poc': dev_poc, 'dev_vah': dev_vah, 'dev_val': dev_val,
            'prior_vp_poc': prior_poc, 'prior_vp_vah': prior_vah, 'prior_vp_val': prior_val,
        }
        rows.append(row)

    out = pd.DataFrame(rows)
    print(f"  Enriched {len(out)} signals in {_time.time()-t0:.1f}s "
          f"(entry_idx misaligned/skipped: {align_fail}, created_idx fallback: {created_fail})")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--sample', type=int, default=None)
    ap.add_argument('--out', type=str, default=str(RESULTS_DIR / 'signals_enriched.csv'))
    args = ap.parse_args()

    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    df = enrich(sample=args.sample)
    df.to_csv(args.out, index=False)
    print(f"Wrote {len(df)} rows -> {args.out}")


if __name__ == '__main__':
    main()
